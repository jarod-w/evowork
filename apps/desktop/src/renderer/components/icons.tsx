export type IconName = keyof typeof PATHS;

export function hasIcon(name: string): boolean {
  return Object.hasOwn(PATHS, name);
}

/**
 * 把 `icon` prop 画出来。
 *
 * 登记过的名字 → SVG；没登记的 → 原样当文本（emoji、`✕`、`⌥1` 这类都靠这条继续工作）。
 */
export function renderIcon(icon: string | undefined): ReactNode {
  if (icon === undefined || icon === '') return null;
  const paths = PATHS[icon];
  if (!paths) return icon;
  return (
    <svg
      className="ew-icon"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.5}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}
